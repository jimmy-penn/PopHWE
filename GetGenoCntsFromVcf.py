def ReadGenotypesFromVcf(vcf_path, num_variants=10):
    """
    Read genotypes from a VCF file using pure Python.
    """
    with gzip.open(vcf_path, 'rt') as f:
        # Skip header lines
        samples = []
        line_count = 0
        variant_count = 0
        
        for line in f:
            line = line.strip()
            if not line:
                continue
                
            if line.startswith('#'):
                # Parse column headers to find sample names
                if line.startswith('#CHROM'):
                    parts = line.split('\t')
                    samples = parts[9:]  # Samples start at column 10
                    num_samples = len(samples)

                    print(f"Total {num_samples} samples: {samples[:5]}... (showing first 5)\n")
                    exit()
                continue
            
            # Parse variant line
            parts = line.split('\t')
            chrom, pos, id_, ref, alt = parts[0], parts[1], parts[2], parts[3], parts[4]
            # Genotype fields start at index 9 (0-based)
            genotype_fields = parts[9:]
            
            if variant_count >= num_variants:
                break
                
            print(f"Variant: {chrom}:{pos} {ref}>{alt}")
            print(f"  ID: {id_ or 'N/A'}")
            print(f"  Genotypes (first 5 samples):")
            
            # Parse first 5 genotypes
            for i in range(min(5, len(genotype_fields))):
                sample_name = samples[i] if i < len(samples) else f"Sample_{i}"
                gt_field = genotype_fields[i].split(':')
                gt = gt_field[0]  # Format is usually 0/0, 0/1, 1/1, ./.
                print(f"    {sample_name}: {gt}")
            
            print("-" * 40)
            variant_count += 1


